
name = "Ashik"
greet = "Hello "

# slice first three elements inddex (0-2)
print(name[0:3])

# slice first four elements index (0-3)
print(name[:4])

#slice elements from index 2 to end
print(name[2:])

# slice string in the step of 2
print(name[::2])

# reverse the string 
print(name[::-1])

# concatination
print(greet+ " " + name)

# string repeatation
print(greet*3)