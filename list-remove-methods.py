fruits = ['apple', 'grapes', 'orange', 'pineapple', 'banana']
print(fruits)
# remove pineapple
fruits.remove('pineapple')
print(fruits)
# remove the element at the end
fruits.pop()
print(fruits)
# remove the elment at index - 1
fruits.pop(1)
print(fruits)
# remove all the element in the list
fruits.clear()
print(fruits)
